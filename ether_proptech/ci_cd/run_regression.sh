#!/bin/bash
set -e

echo "🧪 Запуск регрессионного тестирования системы 'Эфир'..."
echo "-------------------------------------------------------"

# Цвета для вывода
GREEN='\033[0;32m'
RED='\033[0;31m'
NC='\033[0m' # No Color

# 1. Проверка доступности сервисов
echo "🔍 Проверка доступности API и Базы Данных..."
if ! curl -s http://localhost:8080/health > /dev/null; then
    echo -e "${RED}❌ Ошибка: API недоступно. Убедитесь, что контейнеры запущены (make up).${NC}"
    exit 1
fi
echo -e "${GREEN}✅ Сервисы активны.${NC}"

# 2. Запуск pytest с подробным отчетом
echo "📝 Запуск набора тестов на точность RAG и валидацию ответов..."
# Используем docker exec для запуска тестов внутри контейнера приложения
docker-compose exec -T app pytest tests/test_rag_accuracy.py -v --tb=short

if [ $? -eq 0 ]; then
    echo ""
    echo -e "${GREEN}🎉 Все регрессионные тесты пройдены успешно!${NC}"
    echo "✨ Система готова к продакшену: галлюцинации заблокированы, ссылки на ГОСТ присутствуют."
else
    echo ""
    echo -e "${RED}💥 Обнаружены критические ошибки в логике ответов!${NC}"
    echo "⚠️ Запрещено деплоить изменения до устранения причин провала тестов."
    exit 1
fi

# 3. Дополнительная проверка: нагрузочный мини-тест (опционально)
echo "⏱️ Быстрый тест на скорость ответа..."
START=$(date +%s%N)
RESPONSE=$(curl -s -X POST http://localhost:8080/ask \
  -H "Content-Type: application/json" \
  -d '{"question": "Какой уровень шума допустим ночью?"}')
END=$(date +%s%N)

LATENCY=$(( (END - START) / 1000000 )) # в мс

if [[ "$RESPONSE" == *"validated": true"* ]]; then
    echo -e "${GREEN}✅ Ответ валиден. Время отклика: ${LATENCY} мс.${NC}"
else
    echo -e "${RED}⚠️ Ответ не прошел валидацию в runtime.${NC}"
    exit 1
fi

echo "-------------------------------------------------------"
echo "🏁 Регрессия завершена."